from pydantic import BaseModel, Field
from typing import List, Optional, Dict


class InterviewTurnLLMOutput(BaseModel):
    """Structured response from Gemini for each interview conversational turn."""
    reasoning: str = Field(
        description="Brief internal evaluation of the candidate's answer and rationale for the next question."
    )
    spoken_response: str = Field(
        description="The exact words the interviewer will speak. Must be 1 to 3 natural conversational sentences. Absolutely no markdown, no asterisks, no bullet points, and no emojis, as this will be read aloud by Text-to-Speech."
    )
    is_concluded: bool = Field(
        default=False,
        description="Set to true if this is the final closing remark wrapping up the interview."
    )
    suggested_subtopic: Optional[str] = Field(
        default=None,
        description="Current technical focus or subtopic being explored."
    )


class CategoryScore(BaseModel):
    category: str = Field(description="Name of the skill category (e.g., Role & Domain Knowledge, Communication Clarity, Problem Solving & Practical Scenarios).")
    score: int = Field(description="Score between 0 and 100")
    feedback: str = Field(description="Constructive 1-2 sentence feedback for this dimension.")


class InterviewScorecard(BaseModel):
    """Structured evaluation report generated by Gemini at the conclusion of the interview."""
    overall_score: int = Field(description="Overall interview score from 0 to 100.")
    rating: str = Field(description="Overall recommendation: 'Strong Hire', 'Recommended', 'Needs Preparation', or 'Not Ready'.")
    summary: str = Field(description="2-3 sentence executive summary of candidate performance.")
    category_scores: List[CategoryScore] = Field(description="Score breakdown by category.")
    strengths: List[str] = Field(description="List of 3-4 specific strengths demonstrated by the candidate during the interview.")
    improvements: List[str] = Field(description="List of 3-4 actionable spaces for improvement detailing how to answer more effectively.")


class ScorecardRequest(BaseModel):
    topic: str
    history: List[Dict[str, str]]
